const aliases = new Map(Object.entries(SOURCE_ALIASES).map(([label, source]) => [label.toLowerCase(), source]));
const symbolAliases = new Map([
  ["COT:001602_F_CON_GROSS_LE_4_L", "COT2"],
  ["COT:057642_F_SP_L_OTHER", "COT2"],
]);
export const canonicalExchange = (exchange, symbol = "") =>
  symbolAliases.get(`${exchange.toUpperCase()}:${symbol}`) || aliases.get(exchange.toLowerCase()) || exchange;

// Widget EOD availability: tradingview.com/widget-docs/markets/europe/.
// COT is weekly data; the audited FINRA short-volume series are EOD.
const dailySources = new Set(["BER", "COT", "COT2", "DUS", "EUREX", "FWB", "GPW", "HAM", "HAN", "MIL", "MUN", "NEWCONNECT", "SIX", "XETR"]);
export const isDailyOnly = (exchange, symbol) => {
  const source = canonicalExchange(exchange, symbol).toUpperCase();
  return dailySources.has(source) || source === "FINRA" && symbol.endsWith("_SHORT_VOLUME");
};

// Only exact symbols whose widgets showed "only available on TradingView".
// Do not infer a provider-wide restriction or discard historical series.
const restricted = new Map(Object.entries({
  FINRA: ["A4404722", "FNMA4596242", "A4881169"],
  INTOTHEBLOCK: ["BTC_ACTIVEADDRESSES", "0XBTC_ACTIVEADDRESSES"],
  GLASSNODE: ["BTC_SUPPLY", "MARSMI_MEANVOLUMEUSD"],
  COINMETRICS: ["BTC_ACTIVEADDRESSES", "ZRX_TXVOLUMEUSD"],
  LUXSE: ["1FINH", "XS1969589750"],
  NASDAQ: ["AAAAX", "HEIRUCX"],
}).map(([source, symbols]) => [source, new Set(symbols)]));
export const isWidgetRestricted = (exchange, symbol) =>
  restricted.get(canonicalExchange(exchange, symbol).toUpperCase())?.has(symbol) || false;

